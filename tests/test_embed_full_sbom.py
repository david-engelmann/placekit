def test_json_outside_the_sboms_folder_is_not_an_sbom_entry(tmp_path):
    wheel_dir = tmp_path / "dist"
    wheel_dir.mkdir()
    wheel = wheel_dir / "placekit-0.1.0-py3-none-any.whl"
    decoy = f"{DIST_INFO}/data/placekit.cyclonedx.json"
    payloads = {
        METADATA_ENTRY: b"Metadata-Version: 2.1\nName: placekit\nVersion: 0.1.0\n",
        decoy: SLICED_DOCUMENT,
    }
    record_lines = [
        _record_line(name, raw) for name, raw in sorted(payloads.items())
    ]
    record_lines.append(f"{RECORD_ENTRY},,")
    payloads[RECORD_ENTRY] = ("\n".join(record_lines) + "\n").encode("utf-8")
    with zipfile.ZipFile(wheel, "w") as archive:
        for name, raw in payloads.items():
            archive.writestr(name, raw)
    before = wheel.read_bytes()
    replacement = _write(tmp_path, "full.cdx.json", FULL_DOCUMENT)
    result = _run(wheel_dir, replacement)
    assert result.returncode == 1
    assert wheel.read_bytes() == before


def test_archive_comment_survives_the_embed(tmp_path):
    wheel_dir = tmp_path / "dist"
    wheel_dir.mkdir()
    wheel = _build_wheel(wheel_dir, [SLICED_DOCUMENT])
    with zipfile.ZipFile(wheel, "a") as archive:
        archive.comment = b"a recorded archive comment"
    replacement = _write(tmp_path, "full.cdx.json", FULL_DOCUMENT)
    assert _run(wheel_dir, replacement).returncode == 0
    with zipfile.ZipFile(wheel) as archive:
        assert archive.comment == b"a recorded archive comment"
