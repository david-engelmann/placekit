"""Tests for scripts/embed_full_sbom.py, the release SBOM embedder.

Wheels are plain zip archives, so the tests build them in a temp
directory carrying a sliced SBOM (one platform branch of the
tree), then embed the full document and read the result back.
The passing shape is proven against the real guard, imported
from scripts/check_wheel_sbom.py over a fixture Cargo.lock, so
the embedded wheel is judged by the same check the release
workflow runs. Each refusal shape is paired with the passing
shape and verified byte-untouched, so a case cannot pass
vacuously.
"""

from __future__ import annotations

import base64
import hashlib
import importlib.util
import json
import subprocess
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCRIPT = ROOT / "scripts" / "embed_full_sbom.py"
GUARD_SCRIPT = ROOT / "scripts" / "check_wheel_sbom.py"

LOCK_TEXT = """\
# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "placekit"
version = "0.1.0"

[[package]]
name = "placekit-core"
version = "0.1.0"

[[package]]
name = "serde"
version = "1.0.0"
"""

DIST_INFO = "placekit-0.1.0.dist-info"
SBOM_ENTRY = f"{DIST_INFO}/sboms/placekit.cyclonedx.json"
SECOND_SBOM_ENTRY = f"{DIST_INFO}/sboms/other.cyclonedx.json"
RECORD_ENTRY = f"{DIST_INFO}/RECORD"
METADATA_ENTRY = f"{DIST_INFO}/METADATA"
PAYLOAD_ENTRY = "placekit/__init__.py"


def _document(components: list[tuple[str, str]]) -> bytes:
    return json.dumps(
        {
            "bomFormat": "CycloneDX",
            "specVersion": "1.5",
            "metadata": {
                "component": {
                    "type": "library",
                    "name": "placekit",
                    "version": "0.1.0",
                }
            },
            "components": [
                {
                    "type": "library",
                    "name": name,
                    "version": version,
                    "licenses": [{"expression": "MIT"}],
                }
                for name, version in components
            ],
        }
    ).encode("utf-8")


FULL_DOCUMENT = _document([("placekit-core", "0.1.0"), ("serde", "1.0.0")])
SLICED_DOCUMENT = _document([("placekit-core", "0.1.0")])


def _record_line(name: str, raw: bytes) -> str:
    digest = base64.urlsafe_b64encode(hashlib.sha256(raw).digest())
    return f"{name},sha256={digest.decode('ascii').rstrip('=')},{len(raw)}"


def _build_wheel(
    directory: Path,
    sbom_documents: list[bytes],
    record_mode: str = "sound",
) -> Path:
    payloads: dict[str, bytes] = {
        METADATA_ENTRY: b"Metadata-Version: 2.1\nName: placekit\nVersion: 0.1.0\n",
        PAYLOAD_ENTRY: b"__version__ = '0.1.0'\n",
    }
    sbom_names = [SBOM_ENTRY, SECOND_SBOM_ENTRY]
    for name, document in zip(sbom_names, sbom_documents):
        payloads[name] = document
    record_lines = [
        _record_line(name, raw) for name, raw in sorted(payloads.items())
    ]
    if record_mode == "missing-sbom-line":
        record_lines = [
            line for line in record_lines if not line.startswith(SBOM_ENTRY)
        ]
    elif record_mode == "duplicate-sbom-line":
        record_lines.append(_record_line(SBOM_ENTRY, payloads[SBOM_ENTRY]))
    record_lines.append(f"{RECORD_ENTRY},,")
    payloads[RECORD_ENTRY] = ("\n".join(record_lines) + "\n").encode("utf-8")
    wheel = directory / "placekit-0.1.0-py3-none-any.whl"
    with zipfile.ZipFile(wheel, "w") as archive:
        for name, raw in payloads.items():
            archive.writestr(name, raw)
    return wheel


def _run(directory: Path, replacement: Path) -> subprocess.CompletedProcess:
    return subprocess.run(
        [sys.executable, str(SCRIPT), str(directory), str(replacement)],
        capture_output=True,
        text=True,
    )


def _guard():
    spec = importlib.util.spec_from_file_location("check_wheel_sbom", GUARD_SCRIPT)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _embedder():
    spec = importlib.util.spec_from_file_location("embed_full_sbom", SCRIPT)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _write(directory: Path, name: str, raw: bytes) -> Path:
    path = directory / name
    path.write_bytes(raw)
    return path


def test_embedded_wheel_passes_the_real_guard(tmp_path):
    wheel_dir = tmp_path / "dist"
    wheel_dir.mkdir()
    _build_wheel(wheel_dir, [SLICED_DOCUMENT])
    lockfile = _write(tmp_path, "Cargo.lock", LOCK_TEXT.encode("utf-8"))
    guard = _guard()
    assert guard.sbom_problems(wheel_dir, lockfile) != []
    replacement = _write(tmp_path, "full.cdx.json", FULL_DOCUMENT)
    result = _run(wheel_dir, replacement)
    assert result.returncode == 0, result.stdout + result.stderr
    assert guard.sbom_problems(wheel_dir, lockfile) == []
    assert guard.missing_sbom(wheel_dir) == []


def test_record_hashes_match_every_entry_after_embed(tmp_path):
    wheel_dir = tmp_path / "dist"
    wheel_dir.mkdir()
    wheel = _build_wheel(wheel_dir, [SLICED_DOCUMENT])
    replacement = _write(tmp_path, "full.cdx.json", FULL_DOCUMENT)
    assert _run(wheel_dir, replacement).returncode == 0
    with zipfile.ZipFile(wheel) as archive:
        payloads = {name: archive.read(name) for name in archive.namelist()}
    assert payloads[SBOM_ENTRY] == FULL_DOCUMENT
    for line in payloads[RECORD_ENTRY].decode("utf-8").splitlines():
        name, _, rest = line.partition(",")
        if name == RECORD_ENTRY:
            assert rest == ","
            continue
        digest, _, size = rest.partition(",")
        raw = payloads[name]
        assert digest == "sha256=" + base64.urlsafe_b64encode(
            hashlib.sha256(raw).digest()
        ).decode("ascii").rstrip("=")
        assert int(size) == len(raw)


def test_other_entries_and_order_survive_the_embed(tmp_path):
    wheel_dir = tmp_path / "dist"
    wheel_dir.mkdir()
    wheel = _build_wheel(wheel_dir, [SLICED_DOCUMENT])
    with zipfile.ZipFile(wheel) as archive:
        before = [(name, archive.read(name)) for name in archive.namelist()]
    replacement = _write(tmp_path, "full.cdx.json", FULL_DOCUMENT)
    assert _run(wheel_dir, replacement).returncode == 0
    with zipfile.ZipFile(wheel) as archive:
        after = [(name, archive.read(name)) for name in archive.namelist()]
    assert [name for name, _ in after] == [name for name, _ in before]
    for (name, raw), (_, new_raw) in zip(before, after):
        if name not in (SBOM_ENTRY, RECORD_ENTRY):
            assert new_raw == raw


