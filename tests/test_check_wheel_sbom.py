def test_lock_pairs_agree_across_both_parsers(tmp_path):
    guard = load_guard()
    lock = write_lock(tmp_path)
    expected = [("placekit", "0.1.0"), ("placekit-core", "0.1.0"), ("serde", "1.0.0")]
    assert guard.lock_packages(lock) == expected
    assert guard.lock_packages_scan(LOCK_TEXT, lock) == expected


def test_fallback_scan_rejects_a_malformed_lock(tmp_path):
    guard = load_guard()
    lock = write_lock(tmp_path)
    with pytest.raises(guard.LockfileError):
        guard.lock_packages_scan(MALFORMED_LOCK_TEXT, lock)
    with pytest.raises(guard.LockfileError):
        guard.lock_packages_scan('[[package]]\nname = "placekit"\n', lock)


def test_malformed_lock_fails_with_a_named_cause(tmp_path):
    lock = write_lock_text(tmp_path, MALFORMED_LOCK_TEXT)
    make_wheel(tmp_path, "placekit-0.1.0-py3-none-any.whl", sbom=sbom_text())
    result = run_guard(tmp_path, lock)
    assert result.returncode == 1
    assert "FAIL" in result.stdout
    assert "does not parse" in result.stdout
    assert "Traceback" not in result.stderr


